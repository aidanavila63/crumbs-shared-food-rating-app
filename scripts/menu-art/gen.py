# Writes lib/menu-art.ts: the drawn artwork for the ready-made table-menu styles and the
# seasonal decorations. Run: python3 scripts/menu-art/gen.py  (no packages needed)
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from ornaments import ORNAMENTS
from seasonal import SEASONAL
from frames import FRAMES

out = {}
for sid, fn in ORNAMENTS.items():
    top, div, corner, behind = fn()
    out[sid] = {'top': top, 'div': div, 'corner': corner, 'behind': behind}
season = {k: f() for k, f in SEASONAL.items()}
root = os.path.join(os.path.dirname(__file__), '..', '..')
with open(os.path.join(root, 'lib', 'menu-art.ts'), 'w') as f:
    f.write('// Generated by scripts/menu-art/gen.py: do not edit by hand.\n')
    f.write('// Paths are drawn in a 390-wide strip (top), 240x28 (divider), 60x60 (corner) and 300x300 (behind).\n')
    f.write('// Colours are keys (P, S, A, O, O2, X, Y, G, W, K, ink; a trailing d/l = darker/lighter) or #hex.\n')
    f.write("import type { ArtSet, ArtPiece, MenuFrame } from './menu-design.ts'\n\n")
    f.write('export const STYLE_ART: Record<string, ArtSet> = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + '\n\n')
    f.write('export const SEASON_ART: Record<string, ArtPiece> = ' + json.dumps(season, ensure_ascii=False, separators=(',', ':')) + '\n\n')
    f.write('/** Full-page designs for build-your-own menus (see scripts/menu-art/frames.py). */\n')
    f.write('export const FRAMES: MenuFrame[] = ' + json.dumps(FRAMES, ensure_ascii=False, separators=(',', ':')) + '\n')
print('wrote', sum(len(json.dumps(v)) for v in out.values()), 'bytes of style art')
